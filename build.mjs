//#region build
/**
 * Bundle `src/client/ai-worker.js` into the DSH client-bundle format that
 * @deepseek-ai/dsh-client-modules serves and the browser's
 * `window.__ModuleLoader__` consumes.
 *
 * The plugin has no build-time dependencies and no import graph: it is one
 * self-contained source file, so "bundling" is a deterministic wrapper plus a
 * syntax check. Keeping the wrapper here (instead of a dry-dependency bundler)
 * is what lets the plugin install on a machine with nothing but node.
 *
 * Usage: node build.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const PACKAGE_ID = 'dsh-ai-worker';
const sourcePath = join(here, 'src', 'client', 'ai-worker.js');
const outPath = join(here, 'lib', 'client.js');

const source = readFileSync(sourcePath, 'utf8');

/** Indent every line of the inner source by one tab, preserving blank lines. */
const indent = (text) =>
	text
		.split('\n')
		.map((line) => (line.length === 0 ? line : `\t\t${line}`))
		.join('\n');

const banner = `//#region lib/types/client/ai-worker.js
/**
 * 「AI 打工人」browser bundle — generated by build.mjs from
 * src/client/ai-worker.js. Do not edit this file; edit the source and rebuild.
 */
`;

const bundle = `window.__ModuleLoader__.load({
	id: ${JSON.stringify(PACKAGE_ID)},
	factory: (require) => {
		var module = { exports: {} };
		var exports = module.exports;
		Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
		let React = require("react");

${indent(banner)}${indent(source)}

		exports.apply = apply;
		exports.inject = inject;
		return module.exports;
	}
});
`;

// Compile-check the emitted bundle exactly as a browser would parse it. A
// syntax error here would otherwise surface as an unexplained missing widget.
try {
	new Function(bundle);
} catch (error) {
	console.error(`build failed: generated bundle does not parse — ${error.message}`);
	process.exit(1);
}

// Contract check: the client-modules scanner needs these two exports.
if (!/exports\.apply = apply;/.test(bundle) || !/exports\.inject = inject;/.test(bundle)) {
	console.error('build failed: generated bundle does not export apply/inject');
	process.exit(1);
}

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, bundle, 'utf8');

const bundleKb = (Buffer.byteLength(bundle, 'utf8') / 1024).toFixed(1);
const sourceKb = (Buffer.byteLength(source, 'utf8') / 1024).toFixed(1);
console.log(`built ${PACKAGE_ID}: lib/client.js (${bundleKb} kB from ${sourceKb} kB source)`);
//#endregion
